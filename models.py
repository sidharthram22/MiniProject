from django.db import models

ROLE_CHOICES = (
    ('student', 'Student'),
    ('admin', 'Admin'),
)

DIFFICULTY_CHOICES = (
    ('Easy', 'Easy'),
    ('Medium', 'Medium'),
    ('Hard', 'Hard'),
)

class Course(models.Model):
    title = models.CharField(max_length=200, unique=True)
    category = models.CharField(max_length=100, default='Computer Science')
    description = models.TextField(blank=True, default='')

    def __str__(self):
        return self.title

class StudentProfile(models.Model):
    name = models.CharField(max_length=200)
    email = models.EmailField(unique=True)
    password = models.CharField(max_length=200)
    role = models.CharField(max_length=20, choices=ROLE_CHOICES, default='student')
    total_score = models.IntegerField(default=0)
    accuracy = models.CharField(max_length=20, default='85.0%')
    tests_taken = models.IntegerField(default=0)
    avg_rating = models.CharField(max_length=20, default='5.0/5')
    streak_days = models.IntegerField(default=1)
    today_focus = models.CharField(max_length=200, default='Data Structures • Easy')
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.name} ({self.email}) - {self.role}"

    def is_admin(self):
        return self.role == 'admin'

    def enrolled_courses_list(self):
        return [e.course.title for e in self.enrollments.all()]

class Enrollment(models.Model):
    student = models.ForeignKey(StudentProfile, on_delete=models.CASCADE, related_name='enrollments')
    course = models.ForeignKey(Course, on_delete=models.CASCADE, related_name='student_enrollments')
    enrolled_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ('student', 'course')

    def __str__(self):
        return f"{self.student.name} -> {self.course.title}"

class Question(models.Model):
    course = models.ForeignKey(Course, on_delete=models.CASCADE, related_name='questions')
    question_text = models.TextField()
    option_a = models.CharField(max_length=300)
    option_b = models.CharField(max_length=300)
    option_c = models.CharField(max_length=300)
    option_d = models.CharField(max_length=300)
    correct_answer = models.CharField(max_length=1, choices=(('A','A'), ('B','B'), ('C','C'), ('D','D')))
    explanation = models.TextField(blank=True, default='Explanation generated by Claude AI.')
    difficulty = models.CharField(max_length=20, choices=DIFFICULTY_CHOICES, default='Medium')
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"[{self.course.title}] {self.question_text[:50]}..."

class MockTest(models.Model):
    user = models.ForeignKey(StudentProfile, on_delete=models.CASCADE, related_name='mock_tests')
    course = models.ForeignKey(Course, on_delete=models.CASCADE, related_name='mock_tests')
    title = models.CharField(max_length=200)
    difficulty = models.CharField(max_length=20, choices=DIFFICULTY_CHOICES, default='Medium')
    duration_minutes = models.IntegerField(default=15)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.title} - {self.user.name}"

class TestAttempt(models.Model):
    test = models.ForeignKey(MockTest, on_delete=models.CASCADE, related_name='attempts', null=True, blank=True)
    student = models.ForeignKey(StudentProfile, on_delete=models.CASCADE, related_name='attempts')
    course_name = models.CharField(max_length=200, default='General')
    score = models.IntegerField(default=0)
    total_questions = models.IntegerField(default=5)
    percentage = models.FloatField(default=0.0)
    duration_taken_seconds = models.IntegerField(default=0)
    submitted_at = models.DateTimeField(auto_now_add=True)
    answers_json = models.TextField(default='{}')

    def __str__(self):
        return f"Attempt by {self.student.name}: {self.score}/{self.total_questions} ({self.percentage}%)"

class Bookmark(models.Model):
    student = models.ForeignKey(StudentProfile, on_delete=models.CASCADE, related_name='bookmarks')
    question = models.ForeignKey(Question, on_delete=models.CASCADE, related_name='bookmarked_by')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ('student', 'question')

    def __str__(self):
        return f"{self.student.name} bookmarked Question #{self.question.id}"

class Leaderboard(models.Model):
    student = models.ForeignKey(StudentProfile, on_delete=models.CASCADE, related_name='leaderboard_entries')
    course = models.ForeignKey(Course, on_delete=models.CASCADE, related_name='leaderboard_entries', null=True, blank=True)
    total_score = models.IntegerField(default=0)
    rank = models.IntegerField(default=1)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"Rank #{self.rank} - {self.student.name} ({self.total_score} pts)"

class WeeklyChallenge(models.Model):
    course = models.ForeignKey(Course, on_delete=models.CASCADE, related_name='weekly_challenges')
    title = models.CharField(max_length=200)
    description = models.TextField(blank=True, default='')
    week_start = models.DateField()
    week_end = models.DateField()
    active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.title} ({self.course.title})"

class ChallengeParticipation(models.Model):
    challenge = models.ForeignKey(WeeklyChallenge, on_delete=models.CASCADE, related_name='participations')
    student = models.ForeignKey(StudentProfile, on_delete=models.CASCADE, related_name='challenge_participations')
    score = models.IntegerField(default=0)
    rank = models.IntegerField(default=1)
    completed_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.student.name} in {self.challenge.title}: {self.score} pts"

